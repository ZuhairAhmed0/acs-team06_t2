import React from "react";
import ReactDOM from "react-dom/client";
import {BrowserRouter} from "react-router-dom";
import {QueryClient,QueryClientProvider} from "@tanstack/react-query";
import {Toaster} from "sonner";
import App from "./App";
import {AuthProvider} from "./features/AuthProvider";
import "./styles.css";
const client=new QueryClient({defaultOptions:{queries:{staleTime:30000,retry:1,refetchOnWindowFocus:false}}});
ReactDOM.createRoot(document.getElementById("root")).render(<React.StrictMode><QueryClientProvider client={client}><BrowserRouter><AuthProvider><App/><Toaster position="top-center" richColors/></AuthProvider></BrowserRouter></QueryClientProvider></React.StrictMode>);